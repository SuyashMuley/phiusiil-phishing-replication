"""B: final tables (markdown + csv) and figures for the report. Writes only NEW files: results/final_*.csv, results/final_tables.md, results/fig_*.png.

Inputs (read only): results/transfer_runs_v2.csv (raw URLs, 5 seeds), results/transfer_runs_canon.csv (canonical URLs),
results/canonical_vs_raw.csv, results/source_discriminator.csv, results/source_profile.csv.
Usage (from the project folder): .venv/bin/python scripts/16_final_tables_figures.py
Tables use feature set 'all' unless stated; thresholds are the source-validation 95%-recall thresholds from script 07.
"""
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

R = pd.read_csv("results/transfer_runs_v2.csv")
C = pd.read_csv("results/transfer_runs_canon.csv")
R = R[R.featset == "all"]
OTHERS = {"PhiUSIIL": ["GramBeddings", "PhreshPhish"], "GramBeddings": ["PhiUSIIL", "PhreshPhish"], "PhreshPhish": ["PhiUSIIL", "GramBeddings"]}
VARIANTS = ["PhiUSIIL/all", "GramBeddings/all", "GramBeddings/homepage", "PhreshPhish/all"]
MODELS = ["HistGB", "RF", "LR", "MLP", "NGRAM"]


def pairs(v):
    return [("source test", "in-source test")] + [(f"{o} all", o) for o in OTHERS[v.split("/")[0]]]


def ms(g, c, d=2):
    return f"{g[c].mean():.{d}f}±{g[c].std():.{d}f}"


# ---- Table 1: main transfer table (HistGB mean±sd over 5 seeds, model range over the 5 models)
rows = []
for v in VARIANTS:
    for t, tn in pairs(v):
        g = R[(R.variant == v) & (R.target == t)]
        h = g[g.model == "HistGB"]
        per_model = g.groupby("model")[["recall", "fpr"]].mean()
        rows.append({"trained on": v.replace("/all", "").replace("/homepage", " (homepage only)"), "tested on": tn,
                     "n (seed mean)": int(h.n.mean()), "AUROC (HistGB)": ms(h, "auroc"), "recall (HistGB)": ms(h, "recall"),
                     "FPR (HistGB)": ms(h, "fpr"), "oracle FPR@95% (HistGB)": f"{h.oracle_fpr_at_95rec.mean():.2f}",
                     "recall range, 5 models": f"{per_model.recall.min():.2f}-{per_model.recall.max():.2f}",
                     "FPR range, 5 models": f"{per_model.fpr.min():.2f}-{per_model.fpr.max():.2f}"})
t1 = pd.DataFrame(rows)
t1.to_csv("results/final_table_main.csv", index=False)

# ---- Table 2: URL-type slices (HistGB): homepage vs deep on each other dataset
rows = []
for v in VARIANTS:
    for o in OTHERS[v.split("/")[0]]:
        for sl in ("homepage", "deep"):
            h = R[(R.variant == v) & (R.target == f"{o} {sl}") & (R.model == "HistGB")]
            if len(h):
                rows.append({"trained on": v, "tested on": f"{o} {sl}", "n (seed mean)": int(h.n.mean()), "AUROC": ms(h, "auroc") if h.auroc.notna().any() else "n/a (one class)",
                             "recall": ms(h, "recall"), "FPR": ms(h, "fpr") if h.fpr.notna().any() else "n/a (phishing only)"})
t2 = pd.DataFrame(rows)
t2.to_csv("results/final_table_slices.csv", index=False)

# ---- Table 3: PhishTank recall (phishing only; NOT a detection metric on its own)
pt = R[R.target.str.startswith("PhishTank")].groupby(["variant", "model"]).recall.agg(["mean", "std"]).reset_index()
t3 = pt.assign(v=lambda d: d["mean"].round(2).astype(str) + "±" + d["std"].round(2).astype(str)).pivot(index="variant", columns="model", values="v")[MODELS].reset_index()
t3.to_csv("results/final_table_phishtank_recall.csv", index=False)

# ---- Table 4: canonical vs raw cross-source AUROC by model (from canonical_vs_raw.csv)
cv = pd.read_csv("results/canonical_vs_raw.csv")
cross = cv[cv.target != "source test"].groupby(["model", "form"]).auroc.mean().unstack()
ins = cv[cv.target == "source test"].groupby(["model", "form"]).auroc.mean().unstack()
t4 = pd.concat({"cross-source AUROC": cross, "in-source AUROC": ins}, axis=1).loc[MODELS].round(3)
t4.columns = [f"{a}: {b}" for a, b in t4.columns]
t4 = t4.reset_index()
t4.to_csv("results/final_table_canonical.csv", index=False)

# ---- markdown for the report
sd = pd.read_csv("results/source_discriminator.csv").groupby(["cls", "pair", "featset"]).auroc.mean().unstack().round(3).reset_index()
with open("results/final_tables.md", "w") as f:
    f.write("# Final tables (auto-generated by scripts/16_final_tables_figures.py)\n\nThresholds: 95% recall on source validation, fixed. Mean±sd over 5 seeds. Feature set `all`, raw URLs unless stated.\n")
    for title, d in (("Table 1. Transfer at the validation-fixed threshold", t1), ("Table 2. URL-type slices (HistGB)", t2),
                     ("Table 3. PhishTank recall (phishing only, 5 seeds)", t3), ("Table 4. Canonical vs raw URLs, mean AUROC", t4),
                     ("Table 5. Source discriminator AUROC within class", sd)):
        f.write(f"\n## {title}\n\n{d.to_markdown(index=False)}\n")

# ---- Figures (dataset colors fixed across all figures; first three validated categorical slots, light mode)
INK, MUTED, GRID = "#0b0b0b", "#52514e", "#e5e4e0"
COL = {"PhiUSIIL": "#2a78d6", "GramBeddings": "#eb6834", "PhreshPhish": "#1baf7a"}
MARK = {"HistGB": "o", "RF": "s", "LR": "^", "MLP": "D", "NGRAM": "P"}
plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "text.color": INK, "xtick.color": MUTED, "ytick.color": MUTED})

fig, axes = plt.subplots(1, 4, figsize=(15, 4.1), sharex=True, sharey=True)
for ax, v in zip(axes, VARIANTS):
    ax.plot([0, 1], [0, 1], color=MUTED, lw=0.8, ls=":")
    ax.axhline(0.95, color=MUTED, lw=0.8, ls="--")
    for t, tn in pairs(v):
        ent = v.split("/")[0] if t == "source test" else tn
        g = R[(R.variant == v) & (R.target == t)].groupby("model")[["recall", "fpr"]].mean()
        for m in MODELS:
            ax.scatter(g.loc[m, "fpr"], g.loc[m, "recall"], marker=MARK[m], s=46, facecolor=COL[ent] if t != "source test" else "white",
                       edgecolor=COL[ent], linewidth=1.6, zorder=3)
    ax.set_title(v.replace("/all", "").replace("/homepage", " (homepage only)"), fontsize=10, color=INK, loc="left")
    ax.set_xlim(-0.03, 1.03); ax.set_ylim(0.4, 1.02); ax.grid(color=GRID, lw=0.6); ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.set_xlabel("false-positive rate on target")
axes[0].set_ylabel("recall on target")
h1 = [plt.Line2D([], [], marker="o", ls="", markerfacecolor=COL[k], markeredgecolor=COL[k], label=f"tested on {k}") for k in COL]
h1 += [plt.Line2D([], [], marker="o", ls="", markerfacecolor="white", markeredgecolor=MUTED, label="in-source test (hollow)")]
h2 = [plt.Line2D([], [], marker=MARK[m], ls="", markerfacecolor=MUTED, markeredgecolor=MUTED, label=m) for m in MODELS]
h3 = [plt.Line2D([], [], color=MUTED, lw=0.8, ls="--", label="95% recall (validation target)"),
      plt.Line2D([], [], color=MUTED, lw=0.8, ls=":", label="recall = FPR (no skill)")]
fig.legend(handles=h1 + h2 + h3, loc="lower center", ncol=6, frameon=False, fontsize=8.5)
fig.suptitle("Operating point at the threshold fixed on source validation (95% recall): in-source it holds, on other sources it does not", fontsize=10.5, x=0.01, ha="left")
fig.tight_layout(rect=(0, 0.13, 1, 0.95))
fig.savefig("results/fig_operating_points.png", dpi=150)
plt.close(fig)

# canonical vs raw, cross-source AUROC by model (one hue, light -> dark = more formatting removed)
forms = [("raw", "raw URLs", "#a9cbf2"), ("raw_no_scheme_no_www", "scheme and www removed", "#5a9be0"), ("canonical", "canonical (also lowercase, no trailing /)", "#1f5fae")]
fig, ax = plt.subplots(figsize=(7.6, 3.8))
w = 0.26
for i, (k, lab, c) in enumerate(forms):
    ax.bar(np.arange(len(MODELS)) + (i - 1) * (w + 0.02), [cross.loc[m, k] for m in MODELS], width=w, color=c, label=lab)
ax.axhline(0.5, color=MUTED, lw=0.8, ls=":")
ax.set_xticks(np.arange(len(MODELS))); ax.set_xticklabels(MODELS); ax.set_ylim(0.4, 0.95)
ax.set_ylabel("mean cross-source AUROC (8 source-target pairs)")
ax.grid(axis="y", color=GRID, lw=0.6); ax.set_axisbelow(True)
for s in ("top", "right"):
    ax.spines[s].set_visible(False)
ax.legend(frameon=False, fontsize=8.5, loc="upper left")  # HistGB/RF/LR bars stay below 0.7, so the top left is free
ax.set_title("Removing URL formatting does not improve transfer", fontsize=10.5, loc="left")
fig.tight_layout()
fig.savefig("results/fig_canonical_vs_raw.png", dpi=150)
print("wrote final tables and figures")
